export function getAllVariants() {
  return CHORD_GROUPS.flatMap((g) => g.variants);
}

export function findVariantById(id: string) {
  return getAllVariants().find((v) => v.id === id);
}

export function findGroupBySymbol(symbol: string) {
  return CHORD_GROUPS.find(
    (g) => g.symbol.toLowerCase() === symbol.toLowerCase(),
  );
}

export function getPrimaryVariant(symbol: string) {
  const group = findGroupBySymbol(symbol);
  return group?.variants[0];
}
